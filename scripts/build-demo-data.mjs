#!/usr/bin/env node
// Builds data/demo/lexicon.json: the small, real data set behind the Phase 1 demo screens.
// Paradigms are copied verbatim from the DMII Core API, glosses and IPA come from the cached
// Wiktionary extract, and sentences from the cached Tatoeba exports. The Phase 2 pipeline
// replaces this script.
//
//   node scripts/probe-apis.mjs --coverage   (fills .cache/ first)
//   node scripts/build-demo-data.mjs

import { createReadStream, existsSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import { createInterface } from 'node:readline';
import path from 'node:path';
import { CACHE, ROOT, bunzipLines } from './lib/bulk.mjs';

const UA = 'TOLVA-build/0.1 (+https://github.com/KaufmannFredrik/duo-dupe-icelandic)';
const OUT = path.join(ROOT, 'data', 'demo', 'lexicon.json');

const LEMMAS = [
  { lemma: 'hestur', ofl: 'no' },
  { lemma: 'bók', ofl: 'no' },
  { lemma: 'Ísland', ofl: 'no' },
];

// Tatoeba sentence ids used by the demo lesson, stories sample and dictionary examples.
const SENTENCES = ['451938', '389009', '3838979', '738963', '673125', '397461', '509884', '11537171', '695106', '4171415', '3772659', '827619', '983662', '491492'];

const files = {
  kaikki: path.join(CACHE, 'kaikki', 'kaikki.org-dictionary-Icelandic.jsonl'),
  isl: path.join(CACHE, 'tatoeba', 'isl_sentences_detailed.tsv.bz2'),
  links: path.join(CACHE, 'tatoeba', 'isl-eng_links.tsv.bz2'),
  eng: path.join(CACHE, 'tatoeba', 'eng_sentences.tsv.bz2'),
};

async function getJson(url) {
  const res = await fetch(url, { headers: { 'User-Agent': UA }, signal: AbortSignal.timeout(20_000) });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.json();
}

// The API returns a paradigm when one word matches, otherwise a list of candidates with guids.
async function paradigm({ lemma, ofl }) {
  const url = `https://bin.arnastofnun.is/api/ord/${ofl}/${encodeURIComponent(lemma)}`;
  let d = await getJson(url);
  let source = url;
  if (Array.isArray(d) && !d[0]?.bmyndir) {
    const pick = d.find((x) => x.ord === lemma) ?? d[0];
    source = `https://bin.arnastofnun.is/api/ord/${pick.guid}`;
    d = await getJson(source);
  }
  return { source, entry: Array.isArray(d) ? d[0] : d };
}

async function wiktionary(words) {
  const out = Object.fromEntries([...words].map((w) => [w, []]));
  for await (const line of createInterface({ input: createReadStream(files.kaikki), crlfDelay: Infinity })) {
    const m = line.match(/^\{"word": "([^"]+)"/) ?? line.match(/"word": "([^"]+)"/);
    if (!m || !words.has(m[1])) continue;
    const e = JSON.parse(line);
    const sounds = e.sounds ?? [];
    out[e.word].push({
      pos: e.pos,
      ipa: [...new Set(sounds.filter((s) => s.ipa).map((s) => s.ipa))],
      audio: sounds.filter((s) => s.mp3_url || s.ogg_url).map((s) => ({ file: s.audio, mp3: s.mp3_url ?? null, ogg: s.ogg_url ?? null })),
      glosses: (e.senses ?? []).flatMap((s) => s.glosses ?? []).slice(0, 4),
      etymology: e.etymology_text ?? null,
      url: `https://en.wiktionary.org/wiki/${encodeURIComponent(e.word)}#Icelandic`,
    });
  }
  return out;
}

async function tatoeba(ids) {
  const want = new Set(ids);
  const sentences = {};
  for await (const line of bunzipLines(files.isl)) {
    const [id, , text, author] = line.split('\t');
    if (want.has(id)) sentences[id] = { is: text, author, url: `https://tatoeba.org/en/sentences/show/${id}`, en: [] };
  }
  const engIds = new Map();
  for await (const line of bunzipLines(files.links)) {
    const [a, b] = line.split('\t');
    if (sentences[a]) engIds.set(b, a);
  }
  for await (const line of bunzipLines(files.eng)) {
    const [id, , text] = line.split('\t');
    const isl = engIds.get(id);
    if (isl) sentences[isl].en.push({ id, text });
  }
  for (const s of Object.values(sentences)) s.en.sort((a, b) => Number(a.id) - Number(b.id));
  const missing = ids.filter((id) => !sentences[id]);
  if (missing.length) throw new Error(`Tatoeba sentences not found: ${missing.join(', ')}`);
  return sentences;
}

async function main() {
  for (const [name, file] of Object.entries(files)) {
    if (!existsSync(file)) throw new Error(`Missing ${name} cache file ${file}. Run \`node scripts/probe-apis.mjs --coverage\` first (eng_sentences.tsv.bz2 is downloaded separately; see README).`);
  }
  const retrieved = new Date().toISOString();
  const lemmas = {};
  for (const l of LEMMAS) {
    const { source, entry } = await paradigm(l);
    lemmas[l.lemma] = { bin: { source, retrieved, entry } };
  }
  const wikt = await wiktionary(new Set(LEMMAS.map((l) => l.lemma)));
  for (const l of LEMMAS) lemmas[l.lemma].wiktionary = wikt[l.lemma];

  const out = {
    note: 'Demo data for the Phase 1 screens. Generated by scripts/build-demo-data.mjs; replaced by the Phase 2 pipeline.',
    generated: retrieved,
    license: 'CC BY-SA 4.0 (contains DMII Core and Wiktionary data). Tatoeba sentences: CC BY 2.0 FR.',
    sources: {
      bin: 'Beygingarlýsing íslensks nútímamáls (DMII Core). Stofnun Árna Magnússonar í íslenskum fræðum. Höfundur og ritstjóri Kristín Bjarnadóttir. https://bin.arnastofnun.is. Paradigms are reproduced without changes.',
      wiktionary: 'Wiktionary contributors, via kaikki.org (wiktextract). CC BY-SA 4.0.',
      tatoeba: 'Tatoeba (https://tatoeba.org), CC BY 2.0 FR. Each sentence lists its author.',
    },
    lemmas,
    sentences: await tatoeba(SENTENCES),
  };
  await mkdir(path.dirname(OUT), { recursive: true });
  await writeFile(OUT, `${JSON.stringify(out, null, 1)}\n`);
  console.error(`wrote ${path.relative(ROOT, OUT)}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
