#!/usr/bin/env node
// Writes data/numbers.json: every text the number exercises can play (js/engine/numbers.js), for
// scripts/build-audio.py to render in every voice. Run it after changing js/engine/numbers.js,
// then build the audio; tests/numbers.test.mjs checks that both are up to date.
//
//   node scripts/build-numbers.mjs

import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { allTexts } from '../js/engine/numbers.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = {
  note: 'Generated by scripts/build-numbers.mjs from js/engine/numbers.js: the numbers 1 to 99, the ordinals 1st to 10th and the phone numbers as the number exercises say them. scripts/build-audio.py renders each.',
  texts: allTexts(),
};
await writeFile(path.join(ROOT, 'data/numbers.json'), `${JSON.stringify(out, null, 2)}\n`);
console.log(`data/numbers.json: ${out.texts.length} texts`);
